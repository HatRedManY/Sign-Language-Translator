def places_for(animal: str) -> set:
    places = list(PLACES_BY_GROUP[group_of(animal)])
    if places and animal in WILD and "зоопарк" not in places:
        places.append("зоопарк")
    places.extend(SPECIAL_PLACES.get(animal, []))
    return set(places)


