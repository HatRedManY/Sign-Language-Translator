def group_of(animal: str) -> str:
    if animal in BIRDS:
        return "bird"
    if animal in INSECTS:
        return "insect"
    if animal in REPTILES:
        return "reptile"
    if animal in AMPHIBIANS:
        return "amphibian"
    if animal in FISH:
        return "fish"
    return "mammal"


def body_parts_for(animal: str) -> set:
    if animal in BODY_OVERRIDES:
        return set(BODY_OVERRIDES[animal])
    parts = set(BODY_BY_GROUP[group_of(animal)])
    if animal in HOOFED:
        parts.add("копыто")
    if animal in HORNED:
        parts.add("рога")
    if animal not in CLAWLESS:
        parts.add("коготь")
    return parts


